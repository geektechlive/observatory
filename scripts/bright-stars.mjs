// Generates src/lib/orrery/brightStars.ts for the fly-in's sky (#261) from the Yale Bright Star
// Catalogue, 5th revised edition (Hoffleit & Warren 1991; NASA ADC / CDS V/50), which is in the
// public domain. Every star at or brighter than MAX_VMAG, as unit vectors in ecliptic J2000
// (the orrery's axes), with V magnitude and B-V colour.
//
// Usage: node scripts/bright-stars.mjs <path to bsc5.dat> [--count]
// The catalogue: http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz (or CDS, V/50/catalog.gz).
import { readFileSync, writeFileSync } from 'node:fs'

const MAX_VMAG = 3.5
const OBLIQUITY = (23.4392911 * Math.PI) / 180

const [path, flag] = process.argv.slice(2)
if (!path) throw new Error('usage: node scripts/bright-stars.mjs <bsc5.dat> [--count]')
const col = (line, a, b) => line.slice(a - 1, b).trim()

const stars = []
for (const line of readFileSync(path, 'utf8').split('\n')) {
  const vmag = Number.parseFloat(col(line, 103, 107))
  const raH = col(line, 76, 77)
  if (!raH || Number.isNaN(vmag)) continue
  const ra = ((Number(raH) + Number(col(line, 78, 79)) / 60 + Number(col(line, 80, 83)) / 3600) * 15 * Math.PI) / 180
  const sign = col(line, 84, 84) === '-' ? -1 : 1
  const dec = (sign * (Number(col(line, 85, 86)) + Number(col(line, 87, 88)) / 60 + Number(col(line, 89, 90)) / 3600) * Math.PI) / 180
  const bvText = col(line, 110, 114)
  const bv = bvText === '' ? 0 : Number.parseFloat(bvText)
  // Equatorial to ecliptic J2000.
  const xe = Math.cos(dec) * Math.cos(ra)
  const ye = Math.cos(dec) * Math.sin(ra)
  const ze = Math.sin(dec)
  const x = xe
  const y = ye * Math.cos(OBLIQUITY) + ze * Math.sin(OBLIQUITY)
  const z = -ye * Math.sin(OBLIQUITY) + ze * Math.cos(OBLIQUITY)
  stars.push({ hr: Number(col(line, 1, 4)), name: col(line, 5, 14), x, y, z, vmag, bv })
}

if (flag === '--count') {
  for (const m of [2, 3, 3.5, 4, 4.5]) console.log(`V <= ${m}: ${stars.filter((s) => s.vmag <= m).length}`)
  const sirius = stars.find((s) => s.hr === 2491)
  console.log('Sirius', JSON.stringify(sirius))
  process.exit(0)
}

const kept = stars.filter((s) => s.vmag <= MAX_VMAG).sort((a, b) => a.vmag - b.vmag)
const r = (v, d) => Number(v.toFixed(d))
const flat = kept.flatMap((s) => [r(s.x, 4), r(s.y, 4), r(s.z, 4), r(s.vmag, 2), r(s.bv, 2)])
const out = `// Generated by scripts/bright-stars.mjs from the Yale Bright Star Catalogue, 5th revised
// edition (Hoffleit & Warren 1991; NASA ADC / CDS V/50), public domain. Do not edit by hand.
/**
 * The ${kept.length} stars at V <= ${MAX_VMAG} for the fly-in's sky (#261), brightest first: five
 * numbers each, a unit vector in ecliptic J2000 (the orrery's axes; x to the equinox), the V
 * magnitude and the B-V colour.
 */
export const BRIGHT_STARS: readonly number[] = ${JSON.stringify(flat)}

export const BRIGHT_STAR_STRIDE = 5
`
writeFileSync('src/lib/orrery/brightStars.ts', out)
console.log(`wrote ${kept.length} stars, ${out.length} bytes`)
